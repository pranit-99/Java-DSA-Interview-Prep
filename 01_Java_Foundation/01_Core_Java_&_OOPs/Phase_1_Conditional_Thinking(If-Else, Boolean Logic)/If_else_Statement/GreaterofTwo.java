/*Write a Java program that finds the greater of two numbers.

Input:

int a = 25;
int b = 40;

Expected output:

40 is greater */
public class GreaterofTwo {
    public static void main (String args[]){
        int a = 25;
        int b = 40;

        if(b > a){
            System.out.println(b +" is Greater");
        }else{
            System.out.println(a +" is Greater");
        }
    }
}
